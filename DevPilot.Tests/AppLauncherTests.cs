using DevPilot.Models;
using Xunit;

namespace DevPilot.Tests;

public class AppEntryTests
{
    [Fact]
    public void AppEntry_DefaultType_IsExecutable()
    {
        var entry = new AppEntry();
        Assert.Equal(AppEntryType.Executable, entry.Type);
    }

    [Fact]
    public void AppEntry_DefaultIsVisible_IsTrue()
    {
        var entry = new AppEntry();
        Assert.True(entry.IsVisible);
    }

    [Fact]
    public void AppEntry_DefaultRunAsAdmin_IsFalse()
    {
        var entry = new AppEntry();
        Assert.False(entry.RunAsAdmin);
    }

    [Fact]
    public void AppEntryType_HasExpected12Types()
    {
        var types = Enum.GetValues<AppEntryType>();
        Assert.Equal(12, types.Length);
    }

    [Theory]
    [InlineData(AppEntryType.Executable)]
    [InlineData(AppEntryType.Folder)]
    [InlineData(AppEntryType.Url)]
    [InlineData(AppEntryType.PowerShell)]
    [InlineData(AppEntryType.Batch)]
    [InlineData(AppEntryType.Python)]
    [InlineData(AppEntryType.VBScript)]
    [InlineData(AppEntryType.ShellCommand)]
    [InlineData(AppEntryType.Document)]
    [InlineData(AppEntryType.NetworkShare)]
    [InlineData(AppEntryType.Ssh)]
    [InlineData(AppEntryType.Wsl)]
    public void AppEntryType_AllTypesExist(AppEntryType type)
    {
        var entry = new AppEntry { Type = type };
        Assert.Equal(type, entry.Type);
    }

    [Fact]
    public void AppSettings_DefaultApps_IsEmptyList()
    {
        var settings = new AppSettings();
        Assert.NotNull(settings.Apps);
        Assert.Empty(settings.Apps);
    }

    [Fact]
    public void AppEntry_Id_IsAutoGenerated()
    {
        var e1 = new AppEntry();
        var e2 = new AppEntry();
        Assert.NotEqual(e1.Id, e2.Id);
        Assert.Equal(8, e1.Id.Length);
    }
}
